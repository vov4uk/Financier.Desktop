# Handle entries with Cyrillic С in otherwise-Latin strings (typos in source)
$cyrillicMappings = @{
    [char]0x0421 + "ashing" = "Wypłata gotówki"           # Сashing
    [char]0x0421 + "ashier's office" = "Kasa"              # Сashier's office
    [char]0x0421 + "ard replenishment" = "Doładowanie karty" # Сard replenishment
}

$updated = 0
$skipped = 0

foreach ($item in $json) {
    $en = $item.shortDescription.en
    $pl = $item.shortDescription.pl

    if ($pl -ne "") {
        continue
    }

    $translation = $null
    if ($translations.ContainsKey($en)) {
        $translation = $translations[$en]
    } else {
        foreach ($key in $cyrillicMappings.Keys) {
            if ($en -eq $key) {
                $translation = $cyrillicMappings[$key]
                break
            }
        }
    }

    if ($translation -ne $null) {
        $item.shortDescription.pl = $translation
        $updated++
    } else {
        Write-Host "No translation for MCC $($item.mcc): '$en'"
        $skipped++
    }
}

Write-Host "Updated: $updated, Skipped (no translation): $skipped"

# Convert to JSON, then unescape non-ASCII unicode sequences
$result = $json | ConvertTo-Json -Depth 5
$result = [regex]::Replace($result, '\\u([0-9A-Fa-f]{4})', {
    param($match)
    $charCode = [int]('0x' + $match.Groups[1].Value)
    if ($charCode -gt 0x7F) {
        [char]$charCode
    } else {
        $match.Value
    }
})

[System.IO.File]::WriteAllText($filePath, $result, [System.Text.Encoding]::UTF8)
Write-Host "Done. File written to: $filePath"
